alter table public.products
  add column if not exists sale_percent integer,
  add column if not exists sale_active boolean not null default false;

alter table public.products drop constraint if exists products_sale_percent_check;
alter table public.products
  add constraint products_sale_percent_check
  check (sale_percent is null or (sale_percent between 1 and 90));

alter table public.products drop constraint if exists products_season_check;
alter table public.products
  add constraint products_season_check
  check (season is null or season in ('summer','winter','tropical'));

-- The website (and the order function) read prices ONLY through this view.
-- sale_price = price minus sale_percent, but only while sale_active is true.
create or replace view public.website_catalogue as
select
  p.id, p.slug, p.name, p.fabric, p.price,
  case when p.sale_active and coalesce(p.sale_percent, 0) > 0
       then round(p.price * (100 - p.sale_percent) / 100.0)
       else null end as sale_price,
  p.description,
  p.images, p.collection_slug, p.includes, p.sold_out, p.is_new,
  p.website_sort, p.website_added_at,
  p.color, p.season, p.shirt_fabric, p.dupatta_fabric, p.trouser_fabric,
  case when p.sale_active and coalesce(p.sale_percent, 0) > 0
       then p.sale_percent
       else null end as sale_percent
from public.products p
where p.is_visible = true;

alter view public.website_catalogue set (security_invoker = true);
grant select on public.website_catalogue to anon, authenticated;

-- Customer feedback screenshots (images live in the product-images bucket, folder reviews/)
create table if not exists public.reviews (
  id           bigint generated by default as identity primary key,
  image_url    text not null,
  caption      text,
  product_slug text references public.products(slug) on update cascade on delete set null,
  is_visible   boolean not null default true,
  sort_order   integer not null default 0,
  created_at   timestamptz not null default now()
);

alter table public.reviews enable row level security;

drop policy if exists "public read visible reviews" on public.reviews;
create policy "public read visible reviews" on public.reviews
  for select to anon, authenticated using (is_visible);

drop policy if exists "admin all reviews" on public.reviews;
create policy "admin all reviews" on public.reviews
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

begin;

-- ---------- 1. New columns on designs ----------
alter table public.designs
  add column if not exists slug text,
  add column if not exists description text,
  add column if not exists images text[] not null default '{}',
  add column if not exists collection_slug text,
  add column if not exists includes text not null default 'Shirt, Dupatta, Trouser',
  add column if not exists sale_price numeric,
  add column if not exists sold_out boolean not null default false,
  add column if not exists show_on_website boolean not null default false,
  add column if not exists is_new boolean not null default false,
  add column if not exists website_sort integer,
  add column if not exists website_added_at timestamptz not null default now();

-- Give every design without a slug a URL-friendly one made from its name.
with base as (
  select
    ctid as rid,
    coalesce(nullif(trim(both '-' from lower(regexp_replace(trim(name), '[^a-zA-Z0-9]+', '-', 'g'))), ''), 'design') as s
  from public.designs
  where slug is null
),
numbered as (
  select rid, s, row_number() over (partition by s order by rid) as rn from base
)
update public.designs d
set slug = n.s || case when n.rn > 1 then '-' || n.rn::text else '' end
from numbered n
where d.ctid = n.rid;

create unique index if not exists designs_slug_key on public.designs (slug) where slug is not null;

-- ---------- 2. New tables ----------
create table if not exists public.collections (
  slug        text primary key,
  name        text not null,
  parent_slug text references public.collections(slug) on delete set null,
  image_url   text,
  sort_order  integer not null default 0,
  is_visible  boolean not null default true
);

create table if not exists public.home_sections (
  id              bigint generated by default as identity primary key,
  title           text not null,
  -- trending | new | sale | collection
  kind            text not null check (kind in ('trending','new','sale','collection')),
  collection_slug text,
  sort_order      integer not null default 0,
  is_visible      boolean not null default true
);

create table if not exists public.newsletter_subscribers (
  id         bigint generated by default as identity primary key,
  email      text not null unique,
  created_at timestamptz not null default now()
);

create sequence if not exists public.web_order_seq start 1001;

create table if not exists public.web_orders (
  id             bigint generated by default as identity primary key,
  order_number   text not null unique default ('RC-' || nextval('public.web_order_seq')::text),
  created_at     timestamptz not null default now(),
  customer_name  text not null,
  phone          text not null,
  address        text not null,
  city           text not null,
  notes          text,
  payment_method text not null check (payment_method in ('cod','advance')),
  subtotal       numeric not null,
  discount       numeric not null default 0,
  total          numeric not null,
  -- new | confirmed | cancelled
  status         text not null default 'new' check (status in ('new','confirmed','cancelled')),
  ip_hash        text
);

create index if not exists web_orders_phone_created_idx on public.web_orders (phone, created_at desc);
create index if not exists web_orders_ip_created_idx on public.web_orders (ip_hash, created_at desc);

create table if not exists public.web_order_items (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.web_orders(id) on delete cascade,
  design_id  text not null,   -- copy of designs.id (as text, so it works with any id type)
  slug       text not null,
  name       text not null,
  size       text not null,
  qty        integer not null check (qty between 1 and 10),
  unit_price numeric not null
);

-- ---------- 3. Safe public catalogue view (NO cost) ----------
create or replace view public.website_catalogue as
select
  d.id,
  d.slug,
  d.name,
  d.fabric,
  d.price,
  d.sale_price,
  d.description,
  d.images,
  d.collection_slug,
  d.includes,
  d.sold_out,
  d.is_new,
  d.website_sort,
  d.website_added_at
from public.designs d
where d.show_on_website = true
  and d.is_active = true
  and d.slug is not null;

-- ---------- 4. Security (RLS) ----------
alter table public.collections            enable row level security;
alter table public.home_sections          enable row level security;
alter table public.newsletter_subscribers enable row level security;
alter table public.web_orders             enable row level security;
alter table public.web_order_items        enable row level security;

-- Public can READ visible collections and sections
create policy "public read collections" on public.collections
  for select to anon, authenticated using (is_visible);
create policy "public read home sections" on public.home_sections
  for select to anon, authenticated using (is_visible);

-- Public can ADD a newsletter email, but never read the list
create policy "public subscribe" on public.newsletter_subscribers
  for insert to anon, authenticated with check (true);

-- web_orders and web_order_items: NO public policies at all.
-- Only the Edge Function (service role) can write them.
revoke all on public.web_orders      from anon, authenticated;
revoke all on public.web_order_items from anon, authenticated;
revoke all on sequence public.web_order_seq from anon, authenticated;

-- The catalogue view is readable by everyone (it has no cost column)
grant select on public.website_catalogue to anon, authenticated;

commit;


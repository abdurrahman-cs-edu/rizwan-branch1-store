begin;

-- ---------- Who is an admin ----------
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;  -- no policies: not readable through the API

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- Collections and home sections ----------
create table if not exists public.collections (
  slug        text primary key,
  name        text not null,
  parent_slug text references public.collections(slug) on delete set null,
  image_url   text,
  sort_order  integer not null default 0,
  is_visible  boolean not null default true
);

create table if not exists public.home_sections (
  id              bigint generated by default as identity primary key,
  title           text not null,
  -- trending | new | sale | collection
  kind            text not null check (kind in ('trending','new','sale','collection')),
  collection_slug text references public.collections(slug) on delete cascade,
  sort_order      integer not null default 0,
  is_visible      boolean not null default true
);

-- ---------- Products ----------
create table if not exists public.products (
  id               bigint generated by default as identity primary key,
  slug             text not null unique,
  name             text not null,
  fabric           text,
  price            numeric not null check (price >= 0),
  sale_price       numeric check (sale_price is null or sale_price >= 0),
  description      text,
  images           text[] not null default '{}',
  collection_slug  text references public.collections(slug) on update cascade on delete set null,
  includes         text not null default 'Shirt, Dupatta, Trouser',
  sold_out         boolean not null default false,
  is_new           boolean not null default false,
  is_visible       boolean not null default true,   -- false = hidden from the website
  website_sort     integer,
  website_added_at timestamptz not null default now()
);

-- ---------- Orders ----------
create sequence if not exists public.web_order_seq start 1001;

create table if not exists public.web_orders (
  id             bigint generated by default as identity primary key,
  order_number   text not null unique default ('RC-' || nextval('public.web_order_seq')::text),
  created_at     timestamptz not null default now(),
  customer_name  text not null,
  phone          text not null,
  address        text not null,
  city           text not null,
  notes          text,
  payment_method text not null check (payment_method in ('cod','advance')),
  subtotal       numeric not null,
  discount       numeric not null default 0,
  total          numeric not null,
  status         text not null default 'new' check (status in ('new','confirmed','cancelled')),
  ip_hash        text
);
create index if not exists web_orders_phone_created_idx on public.web_orders (phone, created_at desc);
create index if not exists web_orders_ip_created_idx on public.web_orders (ip_hash, created_at desc);

create table if not exists public.web_order_items (
  id         bigint generated by default as identity primary key,
  order_id   bigint not null references public.web_orders(id) on delete cascade,
  design_id  text not null,   -- the product id, saved as text
  slug       text not null,
  name       text not null,
  size       text not null,
  qty        integer not null check (qty between 1 and 10),
  unit_price numeric not null
);

create table if not exists public.newsletter_subscribers (
  id         bigint generated by default as identity primary key,
  email      text not null unique,
  created_at timestamptz not null default now()
);

-- ---------- Public views ----------
-- The website reads products ONLY through this view.
create or replace view public.website_catalogue as
select
  p.id, p.slug, p.name, p.fabric, p.price, p.sale_price, p.description,
  p.images, p.collection_slug, p.includes, p.sold_out, p.is_new,
  p.website_sort, p.website_added_at
from public.products p
where p.is_visible = true;

-- Best sellers of the last 14 days (from website orders only)
create or replace view public.website_trending as
select i.slug, sum(i.qty)::int as units
from public.web_order_items i
join public.web_orders o on o.id = i.order_id
where o.created_at >= now() - interval '14 days'
  and o.status <> 'cancelled'
group by i.slug;

grant select on public.website_catalogue to anon, authenticated;
grant select on public.website_trending  to anon, authenticated;

-- ---------- Security rules (RLS) ----------
alter table public.collections            enable row level security;
alter table public.home_sections          enable row level security;
alter table public.products               enable row level security;
alter table public.web_orders             enable row level security;
alter table public.web_order_items        enable row level security;
alter table public.newsletter_subscribers enable row level security;

-- Public: read visible collections and home sections
create policy "public read collections" on public.collections
  for select to anon, authenticated using (is_visible);
create policy "public read home sections" on public.home_sections
  for select to anon, authenticated using (is_visible);

-- Public: subscribe to the newsletter (cannot read the list)
create policy "public subscribe" on public.newsletter_subscribers
  for insert to anon, authenticated with check (true);

-- Admins: manage everything on the website
create policy "admin all collections" on public.collections
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin all home sections" on public.home_sections
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin all products" on public.products
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin read orders" on public.web_orders
  for select to authenticated using (public.is_admin());
create policy "admin update orders" on public.web_orders
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin read order items" on public.web_order_items
  for select to authenticated using (public.is_admin());
create policy "admin read subscribers" on public.newsletter_subscribers
  for select to authenticated using (public.is_admin());

-- Customers can NOT read or write orders. Only the Edge Function can create
-- them (it uses the service role, which bypasses these rules).

-- ---------- Storage: product photos ----------
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

create policy "public read product images" on storage.objects
  for select using (bucket_id = 'product-images');
create policy "admin add product images" on storage.objects
  for insert to authenticated with check (bucket_id = 'product-images' and public.is_admin());
create policy "admin change product images" on storage.objects
  for update to authenticated using (bucket_id = 'product-images' and public.is_admin());
create policy "admin delete product images" on storage.objects
  for delete to authenticated using (bucket_id = 'product-images' and public.is_admin());

-- ---------- Starting collections and home sections ----------
insert into public.collections (slug, name, parent_slug, sort_order) values
  ('summer', 'Summer', null, 1),
  ('winter', 'Winter', null, 5),
  ('the-ethnic', 'The Ethnic', null, 7),
  ('leather-peach', 'Leather Peach', null, 8)
on conflict (slug) do nothing;

insert into public.collections (slug, name, parent_slug, sort_order) values
  ('premium-dupatta-prints', 'Premium Dupatta Prints', 'summer', 2),
  ('premium-embroidered-lawn', 'Premium Embroidered Lawn', 'summer', 3),
  ('premium-embroidered-lawn-karandi', 'Premium Embroidered Lawn Karandi', 'summer', 4),
  ('print-embroidered-karandi', 'Print Embroidered Karandi', 'winter', 6)
on conflict (slug) do nothing;

insert into public.home_sections (title, kind, sort_order) values
  ('Trending these days', 'trending', 1),
  ('New Arrivals', 'new', 2),
  ('Sale', 'sale', 3);

commit;


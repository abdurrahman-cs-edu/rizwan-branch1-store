--   - admins + is_admin() (who may manage the website)
--   - public views: website_catalogue (safe product list), website_trending
--   - Storage bucket "product-images" for product photos
--   - Security rules (RLS) for all of it
--
-- SAFE TO RUN: the project is new and empty, so there is nothing to lose.
-- HOW: Supabase dashboard -> SQL Editor -> New query -> paste -> Run.
-- It runs as one transaction: if anything fails, nothing is created.
